//! Prints `src/tables.rs`: the committed lookup tables the analyzer reads.
//!
//! The analyzer's numbers feed L2/L3, which must be bit-exact on x86-64 and
//! aarch64 (design §8, D69). So the analyzer itself never calls a libm
//! transcendental — `cos`, `log` and friends can differ in the last bit
//! between libms, and those bits would end up in the hash chain. Every
//! transcendental it needs is a table lookup plus linear interpolation, and
//! the tables are *committed* rather than computed, the same trick as
//! `lm gen-trig` (the Q14 sine table in lm-core).
//!
//! This generator runs on the host, where floating point is allowed. Do not
//! edit its output by hand. Regenerate with:
//!
//! ```text
//! cargo run -p lm-vox --example gen-tables > src/tables.rs.new &&
//!     mv src/tables.rs.new src/tables.rs
//! ```
//!
//! (Redirecting straight into `src/tables.rs` would truncate the file before
//! the build that reads it.)

/// 4096 entries over the quarter turn is `pi/2/4096 = 3.83e-4` rad per step;
/// linear interpolation error is below `1e-8` everywhere, which is far under
/// anything the protocol can represent.
const COS_Q: usize = 4096;
/// Q15 scale: 32768 is 1.0.
const Q15: f64 = 32_768.0;
/// 513 entries of log2 over the mantissa range [1, 2] (the last entry is
/// log2(2) = 1, so interpolation at the top edge is a plain table read).
/// Interpolation error stays under 7e-6 in log2, i.e. under 0.01 cent in
/// pitch.
const LOG2_Q: usize = 512;
/// 513 entries of 2^u over [0, 1] (the last entry is 2): the inverse of
/// LOG2_Q16, for the cents<->Hz and formant-field<->Hz conversions.
const EXP2_Q: usize = 512;
/// Q16 scale for the log/pow tables: 65536 is 1.0.
const Q16: f64 = 65_536.0;
/// Table entries per line.
const VALUES_PER_LINE: usize = 8;

/// One committed table, printed as a `pub const` array.
fn emit(name: &str, doc: &str, values: Vec<i64>) {
    println!("/// {doc}");
    println!(
        "pub const {name}: [{}; {}] = [",
        ty_of(&values),
        values.len()
    );
    let mut line = String::from("    ");
    for (i, v) in values.iter().enumerate() {
        line.push_str(&v.to_string());
        line.push(',');
        if (i + 1) % VALUES_PER_LINE == 0 || i + 1 == values.len() {
            println!("{line}");
            line = String::from("    ");
        } else {
            line.push(' ');
        }
    }
    println!("];");
}

/// i16 for the cosine (it fits Q15), i32 for the Q16 tables.
fn ty_of(values: &[i64]) -> &'static str {
    if values
        .iter()
        .all(|v| *v >= i16::MIN as i64 && *v <= i16::MAX as i64)
    {
        "i16"
    } else {
        "i32"
    }
}

fn main() {
    print!(
        "\
//! Lookup tables for the analyzer, generated by `gen-tables` (the example).
//!
//! Do not edit by hand. Regenerate with:
//! `cargo run -p lm-vox --example gen-tables > src/tables.rs.new && mv src/tables.rs.new src/tables.rs`
//!
//! The analyzer reads these instead of calling libm (cos/log can differ in
//! the last bit between machines; a committed table reads identically
//! everywhere, like lm-core's Q14 sine table). COS_Q15 is cos over the first
//! quarter turn, 4096 entries of Q15; LOG2_Q16 is log2 over [1, 2], 513
//! entries of Q16; EXP2_Q16 is its inverse, 2^u over [0, 1]. All are used
//! with linear interpolation.

"
    );

    let cos: Vec<i64> = (0..COS_Q)
        .map(|i| {
            let c = ((i as f64) * std::f64::consts::FRAC_PI_2 / (COS_Q as f64)).cos();
            // cos(0) must not round past Q15_ONE into i16 overflow.
            ((c * Q15).round() as i64).min(32_767)
        })
        .collect();
    emit(
        "COS_Q15",
        "cos over the first quarter turn: entry i is round(32768 * cos(i * pi / 2 / 4096)).",
        cos,
    );
    println!();

    let log2: Vec<i64> = (0..=LOG2_Q)
        .map(|i| {
            let v = (1.0 + (i as f64) / (LOG2_Q as f64)).log2();
            (v * Q16).round() as i64
        })
        .collect();
    emit(
        "LOG2_Q16",
        "log2 over [1, 2]: entry i is round(65536 * log2(1 + i / 512)).",
        log2,
    );
    println!();

    let exp2: Vec<i64> = (0..=EXP2_Q)
        .map(|i| {
            let v = (2.0_f64).powf((i as f64) / (EXP2_Q as f64));
            (v * Q16).round() as i64
        })
        .collect();
    emit(
        "EXP2_Q16",
        "2^u over [0, 1]: entry i is round(65536 * 2^(i / 512)).",
        exp2,
    );
}
